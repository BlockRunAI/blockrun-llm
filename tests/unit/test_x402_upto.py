class TestReferenceVector:
    def _option(self, sponsoring: bool):
        pr = {"x402Version": 2, "accepts": [REQ]}
        if sponsoring:
            pr["extensions"] = {"eip2612GasSponsoring": {"info": {"version": "1"}}}
        option = find_upto_option(pr)
        assert option is not None
        return option, pr

    def test_constants_match_reference(self):
        assert PERMIT2_ADDRESS == VECTOR["constants"]["PERMIT2_ADDRESS"]
        assert X402_UPTO_PERMIT2_PROXY_ADDRESS == VECTOR["constants"]["x402UptoPermit2ProxyAddress"]

    def test_permit2_typed_data_hash_matches_viem(self):
        option, _ = self._option(False)
        typed = permit2_witness_typed_data(
            chain_id=8453,
            token=option.usdc,
            amount=option.amount,
            nonce=NONCE_0x11,
            deadline=NOW + 300,
            pay_to=option.pay_to,
            facilitator=option.facilitator,
        )
        digest = _hash_eip191_message(encode_typed_data(full_message=typed))
        assert "0x" + digest.hex() == VECTOR["permit2Digest"]

    def test_eip2612_typed_data_hash_matches_viem(self):
        option, _ = self._option(True)
        typed = eip2612_permit_typed_data(
            domain=option.domain,
            owner=TEST_ACCOUNT.address,
            value=option.amount,
            nonce=7,
            deadline=NOW + 300,
        )
        digest = _hash_eip191_message(encode_typed_data(full_message=typed))
        assert "0x" + digest.hex() == VECTOR["eip2612Digest"]

    def test_bare_payload_is_byte_identical(self):
        option, pr = self._option(False)
        payment = decode(
            create_upto_payment_payload(
                TEST_ACCOUNT,
                option,
                resource_url="https://blockrun.ai/api/v1/chat/completions",
                resource_description="d",
                extensions=pr.get("extensions"),
                now=NOW,
                nonce=NONCE_0x11,
            )
        )
        assert payment["payload"] == VECTOR["bare"]["payload"]
        assert "eip2612GasSponsoring" not in payment["extensions"]

    def test_sponsored_payload_is_byte_identical(self):
        option, pr = self._option(True)
        payment = decode(
            create_upto_payment_payload(
                TEST_ACCOUNT,
                option,
                resource_url="https://blockrun.ai/api/v1/chat/completions",
                resource_description="d",
                extensions=pr["extensions"],
                permit_nonce=7,
                now=NOW,
                nonce=NONCE_0x11,
            )
        )
        expected = VECTOR["sponsored"]
        assert payment["payload"] == expected["payload"]
        info = payment["extensions"]["eip2612GasSponsoring"]["info"]
        assert info == expected["extensions"]["eip2612GasSponsoring"]["info"]

    def test_permit_value_equals_permitted_amount(self):
        """The upto proxy reverts (Permit2612AmountMismatch) unless the EIP-2612
        permit's value is exactly the Permit2 permitted amount — so MaxUint256
        (or anything but the ceiling) is a signed payment that cannot settle."""
        option, pr = self._option(True)
        payment = decode(
            create_upto_payment_payload(
                TEST_ACCOUNT,
                option,
                resource_url="u",
                resource_description="d",
                extensions=pr["extensions"],
                permit_nonce=7,
            )
        )
        info = payment["extensions"]["eip2612GasSponsoring"]["info"]
        permitted = payment["payload"]["permit2Authorization"]["permitted"]["amount"]
        assert info["amount"] == permitted == REQ["amount"]
        # …and the signature is over that value, not just the JSON field.
        typed = eip2612_permit_typed_data(
            domain=option.domain,
            owner=TEST_ACCOUNT.address,
            value=int(permitted),
            nonce=7,
            deadline=int(info["deadline"]),
        )
        signer = Account.recover_message(
            encode_typed_data(full_message=typed), signature=info["signature"]
        )
        assert signer == TEST_ACCOUNT.address

    def test_signatures_recover_to_the_payer(self):
        auth = VECTOR["sponsored"]["payload"]["permit2Authorization"]
        typed = permit2_witness_typed_data(
            chain_id=8453,
            token=auth["permitted"]["token"],
            amount=int(auth["permitted"]["amount"]),
            nonce=int(auth["nonce"]),
            deadline=int(auth["deadline"]),
            pay_to=auth["witness"]["to"],
            facilitator=auth["witness"]["facilitator"],
        )
        signer = Account.recover_message(
            encode_typed_data(full_message=typed),
            signature=VECTOR["sponsored"]["payload"]["signature"],
        )
        assert signer == TEST_ACCOUNT.address


class TestPayloadEnvelope:
    def test_envelope_matches_exact_and_echoes_the_requirement(self):
        pr = payment_required(sponsoring=True)
        option = find_upto_option(pr)
        payment = decode(
            create_upto_payment_payload(
                TEST_ACCOUNT,
                option,
                resource_url="https://blockrun.ai/api/v1/chat/completions",
                resource_description="AI model inference",
                extensions=pr["extensions"],
                permit_nonce=3,
            )
        )
        assert payment["x402Version"] == 2
        assert payment["accepted"] == upto_entry()  # verbatim, facilitatorAddress included
        assert payment["resource"]["url"] == "https://blockrun.ai/api/v1/chat/completions"
        # BlockRun's builder service code merged in, the server's app code kept.
        assert payment["extensions"]["builder-code"]["info"] == {"a": ["app"], "s": ["blockrun"]}
        # @x402/core merge semantics: server-declared fields stay, client fields added.
        info = payment["extensions"]["eip2612GasSponsoring"]["info"]
        assert info["description"] == SPONSORING_DECL["info"]["description"]
        assert info["version"] == "1"
        assert info["spender"] == PERMIT2_ADDRESS
        assert info["amount"] == UPTO_CEILING  # must equal permitted.amount
        assert info["nonce"] == "3"
        assert info["deadline"] == payment["payload"]["permit2Authorization"]["deadline"]
        assert payment["extensions"]["eip2612GasSponsoring"]["schema"] == {"type": "object"}

    def test_nonce_is_random_256_bit_decimal(self):
        option = find_upto_option(payment_required())
        nonces = {
            decode(
                create_upto_payment_payload(
                    TEST_ACCOUNT, option, resource_url="u", resource_description="d"
                )
            )["payload"]["permit2Authorization"]["nonce"]
            for _ in range(3)
        }
        assert len(nonces) == 3
        assert all(n.isdigit() and int(n) < 2**256 for n in nonces)

    def test_merge_extensions_non_object_replaces(self):
        assert merge_extensions(
            {"a": 1, "b": {"x": 1}}, {"a": {"y": 2}, "b": {"x": 9, "z": 3}}
        ) == {
            "a": {"y": 2},
            "b": {"x": 1, "z": 3},
        }


