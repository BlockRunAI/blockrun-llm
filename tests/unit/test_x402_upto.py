def exact_entry(amount: str = EXACT_AMOUNT) -> dict[str, Any]:
    return {
        "scheme": "exact",
        "network": "eip155:8453",
        "amount": amount,
        "asset": USDC_BASE,
        "payTo": TEST_RECIPIENT,
        "maxTimeoutSeconds": 300,
        "extra": {"name": "USD Coin", "version": "2"},
    }


def upto_entry(amount: str = UPTO_CEILING, **overrides: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "scheme": "upto",
        "network": "eip155:8453",
        "amount": amount,
        "asset": USDC_BASE,
        "payTo": TEST_RECIPIENT,
        "maxTimeoutSeconds": 300,
        "extra": {"name": "USD Coin", "version": "2", "facilitatorAddress": FACILITATOR},
    }
    entry.update(overrides)
    return entry


def payment_required(
    *, with_upto: bool = True, sponsoring: bool = False, upto: dict | None = None
) -> dict[str, Any]:
    accepts = [exact_entry()]
    if with_upto:
        accepts.append(upto or upto_entry())
    extensions: dict[str, Any] = {"builder-code": {"info": {"a": ["app"]}}}
    if sponsoring:
        extensions["eip2612GasSponsoring"] = SPONSORING_DECL
    return {
        "x402Version": 2,
        "accepts": accepts,
        "resource": {
            "url": "https://blockrun.ai/api/v1/chat/completions",
            "description": "AI model inference",
        },
        "extensions": extensions,
    }


def b64(obj: dict) -> str:
    return base64.b64encode(json.dumps(obj).encode()).decode()


def decode(header: str) -> dict[str, Any]:
    return json.loads(base64.b64decode(header))


def settlement_header(amount: str | None = None) -> str:
    data: dict[str, Any] = {
        "success": True,
        "transaction": "0x" + "ab" * 32,
        "network": "eip155:8453",
    }
    if amount is not None:
        data["amount"] = amount
    return b64(data)


class Gateway:
    """A MockTransport gateway: 402 on the unpaid call, then scripted answers
    for each paid call. Records every PAYMENT-SIGNATURE it receives."""

    def __init__(
        self,
        pr: dict[str, Any],
        paid: list[httpx.Response] | None = None,
        *,
        price_usd: str | None = None,
        header: bool = True,
    ):
        self.pr = pr
        self.paid = list(paid or [])
        self.signed: list[dict[str, Any]] = []
        self.price_usd = price_usd
        self.header = header

    def __call__(self, request: httpx.Request) -> httpx.Response:
        sig = request.headers.get("PAYMENT-SIGNATURE")
        if sig is None:
            if self.header:
                return httpx.Response(
                    402,
                    json={"error": "Payment Required"},
                    headers={"payment-required": b64(self.pr)},
                )
            body: dict[str, Any] = {**self.pr, "x402": True}
            if self.price_usd is not None:
                body["price"] = {"amount": self.price_usd, "currency": "USD"}
            return httpx.Response(402, json=body)
        self.signed.append(decode(sig))
        if self.paid:
            return self.paid.pop(0)
        return httpx.Response(
            200, json=build_chat_response(), headers={"PAYMENT-RESPONSE": settlement_header()}
        )

    @property
    def schemes(self) -> list[str]:
        return [s["accepted"]["scheme"] for s in self.signed]


def ok(amount: str | None = None) -> httpx.Response:
    return httpx.Response(
        200, json=build_chat_response(), headers={"PAYMENT-RESPONSE": settlement_header(amount)}
    )


def verify_failed() -> httpx.Response:
    return httpx.Response(
        402, json={"error": "Payment verification failed", "debug": "permit2_allowance_required"}
    )


def sync_client(gw: Gateway, **kwargs: Any) -> LLMClient:
    client = LLMClient(private_key=TEST_PRIVATE_KEY, **kwargs)
    client._client = httpx.Client(transport=httpx.MockTransport(gw))
