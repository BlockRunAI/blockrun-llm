class Chain:
    """Scripted chain state for the upto reads (sync and async)."""

    def __init__(
        self,
        *,
        balance: int = 10**9,
        allowance: int = 10**9,
        nonce: int = 7,
        fail: bool = False,
    ):
        self.balance, self.allowance, self.nonce, self.fail = balance, allowance, nonce, fail
        self.reads = 0

    def state(self, option: upto.UptoOption, owner: str) -> UptoChainState:
        self.reads += 1
        if self.fail:
            raise upto.UptoUnavailable("every RPC failed")
        assert owner == TEST_ACCOUNT.address
        need = option.gas_sponsoring and self.allowance < option.amount
        return UptoChainState(self.balance, self.allowance, self.nonce if need else None)

    def install(self, monkeypatch: pytest.MonkeyPatch) -> Chain:
        monkeypatch.setattr(upto, "read_upto_chain_state", self.state)

        async def astate(option: upto.UptoOption, owner: str) -> UptoChainState:
            return self.state(option, owner)

        monkeypatch.setattr(upto, "aread_upto_chain_state", astate)
        return self


