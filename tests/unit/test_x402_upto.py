        assert gw.schemes == ["upto"]
        info = gw.signed[0]["extensions"]["eip2612GasSponsoring"]["info"]
        assert info["nonce"] == "11" and info["amount"] == UPTO_CEILING
        # The permit's value must equal Permit2's permitted amount.
        assert (
            gw.signed[0]["payload"]["permit2Authorization"]["permitted"]["amount"] == UPTO_CEILING
        )
        assert info["from"] == TEST_ACCOUNT.address

