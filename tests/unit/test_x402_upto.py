"""x402 ``upto`` (Permit2) payments.

What these tests pin:

1. **Wire compatibility** — for fixed inputs the Python signer produces the
   byte-identical Permit2 witness signature, EIP-2612 permit signature and
   payload fields as the official ``@x402/evm`` 2.28.0 client. The vector in
   ``x402_upto_reference_vector.json`` was generated by that client
   (``scripts/gen-upto-vector.mjs``), not by this code.
2. **Selection policy** — upto is chosen only when the 402 offers it with a
   facilitator, the wallet holds the ceiling, and Permit2 may already pull it
   or the gateway sponsors the approval. Every other case — and every error —
   signs ``exact`` exactly as before.
3. **Rejection** — an upto payment the gateway refuses before serving anything
   is retried once with exact; a 2xx is never retried.
4. **Accounting** — the upto ceiling is never booked as a confirmed charge.
"""

