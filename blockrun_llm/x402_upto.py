def permit2_witness_typed_data(
    *,
    chain_id: int,
    token: str,
    amount: int,
    nonce: int,
    deadline: int,
    pay_to: str,
    facilitator: str,
    valid_after: int = 0,
) -> dict[str, Any]:
    """The full EIP-712 message the upto payer signs (Permit2 domain, no version)."""
    return {
        "types": {
            "EIP712Domain": [
                {"name": "name", "type": "string"},
                {"name": "chainId", "type": "uint256"},
                {"name": "verifyingContract", "type": "address"},
            ],
            **UPTO_PERMIT2_WITNESS_TYPES,
        },
        "primaryType": "PermitWitnessTransferFrom",
        "domain": {
            "name": "Permit2",
            "chainId": chain_id,
            "verifyingContract": PERMIT2_ADDRESS,
        },
        "message": {
            "permitted": {"token": token, "amount": amount},
            "spender": X402_UPTO_PERMIT2_PROXY_ADDRESS,
            "nonce": nonce,
            "deadline": deadline,
            "witness": {"to": pay_to, "facilitator": facilitator, "validAfter": valid_after},
        },
    }


def eip2612_permit_typed_data(
    *, domain: dict[str, Any], owner: str, value: int, nonce: int, deadline: int
) -> dict[str, Any]:
    """The full EIP-712 message for a USDC ``permit(owner, Permit2, value, …)``."""
    return {
        "types": {
            "EIP712Domain": [
                {"name": "name", "type": "string"},
                {"name": "version", "type": "string"},
                {"name": "chainId", "type": "uint256"},
                {"name": "verifyingContract", "type": "address"},
            ],
            **EIP2612_PERMIT_TYPES,
        },
        "primaryType": "Permit",
        "domain": dict(domain),
        "message": {
            "owner": owner,
            "spender": PERMIT2_ADDRESS,
            "value": value,
            "nonce": nonce,
            "deadline": deadline,
        },
    }


def _sign(account: Any, full_message: dict[str, Any]) -> str:
    return signature_hex(account.sign_message(encode_typed_data(full_message=full_message)))


def merge_extensions(
    server: dict[str, Any] | None, client: dict[str, Any] | None
) -> dict[str, Any]:
    """Port of ``x402Client.mergeExtensions`` (@x402/core): client data adds
    fields, server-declared fields stay intact; a non-object replaces."""
    if not client:
        return dict(server or {})
    if not server:
        return dict(client)
    merged = dict(server)
    for key, client_value in client.items():
        server_value = merged.get(key)
        if not isinstance(server_value, dict) or not isinstance(client_value, dict):
            merged[key] = client_value
            continue
        merged[key] = _merge_server_wins(server_value, client_value)
    return merged


def _merge_server_wins(server: dict[str, Any], client: dict[str, Any]) -> dict[str, Any]:
    out = dict(server)
    for field, client_field in client.items():
        server_field = out.get(field)
        if isinstance(server_field, dict) and isinstance(client_field, dict):
            out[field] = _merge_server_wins(server_field, client_field)
        elif field not in out:
            out[field] = client_field
    return out


def create_upto_payment_payload(
    account: Any,
    option: UptoOption,
    *,
    resource_url: str,
    resource_description: str,
    extensions: dict[str, Any] | None = None,
    permit_nonce: int | None = None,
    now: int | None = None,
    nonce: int | None = None,
) -> str:
    """Sign an upto payment and return the base64 ``PAYMENT-SIGNATURE`` value.

    ``permit_nonce`` set → also sign the EIP-2612 permit (USDC → Permit2 for the
    ceiling) and attach it as ``extensions.eip2612GasSponsoring.info``.
    ``now`` / ``nonce`` exist for deterministic tests.
    """
    now = int(time.time()) if now is None else now
    deadline = now + option.max_timeout_seconds
    permit2_nonce = int.from_bytes(secrets.token_bytes(32), "big") if nonce is None else nonce
    owner = to_checksum_address(account.address)

    signature = _sign(
        account,
        permit2_witness_typed_data(
            chain_id=option.chain_id,
            token=option.usdc,
            amount=option.amount,
            nonce=permit2_nonce,
            deadline=deadline,
            pay_to=option.pay_to,
            facilitator=option.facilitator,
        ),
    )

    merged = with_builder_code_service_code(extensions)
    if permit_nonce is not None:
        info = {
            "from": owner,
            "asset": option.usdc,
            "spender": PERMIT2_ADDRESS,
            # Must equal permitted.amount: the proxy reverts otherwise.
            "amount": str(option.amount),
            "nonce": str(permit_nonce),
            "deadline": str(deadline),
            "signature": _sign(
                account,
                eip2612_permit_typed_data(
                    domain=option.domain,
                    owner=owner,
                    value=option.amount,
                    nonce=permit_nonce,
                    deadline=deadline,
                ),
            ),
            "version": EIP2612_GAS_SPONSORING_VERSION,
        }
        merged = merge_extensions(merged, {EIP2612_GAS_SPONSORING_KEY: {"info": info}})

    payment = {
        "x402Version": 2,
        "resource": {
            "url": resource_url,
            "description": resource_description,
            "mimeType": "application/json",
        },
        # The requirement exactly as offered: a server may match `accepted`
        # against its own accepts entry field for field.
        "accepted": dict(option.requirement),
        "payload": {
            "signature": signature,
            "permit2Authorization": {
                "from": owner,
                "permitted": {"token": option.usdc, "amount": str(option.amount)},
                "spender": X402_UPTO_PERMIT2_PROXY_ADDRESS,
                "nonce": str(permit2_nonce),
                "deadline": str(deadline),
                "witness": {
                    "to": option.pay_to,
                    "facilitator": option.facilitator,
                    "validAfter": "0",
                },
            },
        },
        "extensions": merged,
    }
    return base64.b64encode(json.dumps(payment).encode()).decode()


# ---------------------------------------------------------------------------
# One call: decide, then sign — or return None for exact
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class UptoPayment:
    header: str  # base64 PAYMENT-SIGNATURE
    amount: int  # signed ceiling, micro-USDC
    permit_attached: bool

    @property
    def ceiling_usd(self) -> float:
        return self.amount / 1e6


def _sign_planned(
    account: Any,
    option: UptoOption,
    state: UptoChainState,
    *,
    resource_url: str,
    resource_description: str,
    extensions: dict[str, Any] | None,
) -> UptoPayment | None:
    needs_permit = plan_upto(option, state)
    if needs_permit is None:
        return None
    if not needs_permit:
        # Permit2 can already pull the ceiling: no permit, whatever is in flight.
        header = create_upto_payment_payload(
            account,
            option,
            resource_url=resource_url,
            resource_description=resource_description,
            extensions=extensions,
        )
        return UptoPayment(header, option.amount, permit_attached=False)

    assert state.permit_nonce is not None  # plan_upto returns True only with one
    now = int(_now())
    if not _claim_permit_slot(
        option.network, account.address, state.permit_nonce, now + option.max_timeout_seconds
    ):
        logger.debug("x402 upto: a sponsored permit is still in flight; using exact")
        return None
    try:
        header = create_upto_payment_payload(
            account,
            option,
            resource_url=resource_url,
            resource_description=resource_description,
            extensions=extensions,
            permit_nonce=state.permit_nonce,
            now=now,
        )
    except Exception:
        _release_permit_slot(option.network, account.address, state.permit_nonce)
        raise
    return UptoPayment(header, option.amount, permit_attached=True)


def try_upto_payment(
    account: Any,
    option: UptoOption,
    payment_required: dict[str, Any],
    *,
    resource_url: str,
    resource_description: str,
    within_limits: Callable[[float], bool],
    read_state: Callable[[UptoOption, str], UptoChainState] | None = None,
) -> UptoPayment | None:
    """Sign upto if the policy allows it; ``None`` (never an exception) means use exact."""
    try:
        if not within_limits(option.ceiling_usd):
            logger.debug("x402 upto: ceiling $%.6f breaches a spend limit", option.ceiling_usd)
            return None
        reader = read_state or read_upto_chain_state
        state = reader(option, account.address)
        return _sign_planned(
            account,
            option,
            state,
            resource_url=resource_url,
            resource_description=resource_description,
            extensions=payment_required.get("extensions"),
        )
    except Exception as exc:
        logger.debug("x402 upto: falling back to exact (%s: %s)", type(exc).__name__, exc)
        return None


