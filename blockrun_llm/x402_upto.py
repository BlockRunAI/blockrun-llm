"""
x402 ``upto`` scheme (Permit2) for BlockRun's EVM gateways.

Under ``exact`` the payer signs an EIP-3009 authorization for a fixed pre-call
quote, so a discount the gateway only learns after the call — a prompt-cache
hit, a short answer — can never reach an x402 caller. Under ``upto`` the payer
signs a Permit2 ``PermitWitnessTransferFrom`` for a CEILING, and the gateway
settles the ACTUAL amount (never more than the ceiling) once the call is done.

A gateway that offers upto lists it after ``exact`` in ``accepts``. This module
decides whether to take it, and signs it. The rule is that choosing upto must
never be worse than today's ``exact``:

* It is taken only when the 402 offers an EVM upto option carrying
  ``extra.facilitatorAddress`` for a network in :data:`EVM_NETWORKS`, and
* the wallet holds at least the ceiling in USDC, and
* Permit2 may already pull the ceiling (USDC ``allowance(owner, Permit2)``), or
  the 402 declares the ``eip2612GasSponsoring`` extension, in which case the
  wallet signs a gasless EIP-2612 permit to Permit2 and the facilitator submits
  the approval — so a wallet holding no ETH can still use upto.

Anything else — no RPC answer, a signing error, a ceiling over a spend limit, a
sponsored permit already in flight for this wallet — falls back to ``exact``
silently (debug log only). Solana is untouched: it only ever pays ``exact``.

Semantics match the official ``@x402/evm`` 2.28.0 client (``UptoEvmScheme``,
``createUptoPermit2Payload``, ``trySignEip2612PermitExtension``); the unit tests
pin a vector generated by that client (``scripts/gen-upto-vector.mjs``).

The private key is used ONLY for local signing and NEVER leaves the client.
"""

