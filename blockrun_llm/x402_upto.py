@dataclass(frozen=True)
class UptoOption:
    """A 402's upto requirement, validated against the SDK's own chain table."""

    requirement: dict[str, Any]  # the accepts entry, echoed back as `accepted`
    network: str  # canonical CAIP-2
    chain_id: int
    usdc: str
    domain: dict[str, Any]  # USDC's EIP-712 domain (SDK-owned, never the 402's)
    rpcs: tuple[str, ...]
    amount: int  # ceiling, micro-USDC
    pay_to: str
    facilitator: str
    max_timeout_seconds: int
    gas_sponsoring: bool  # the 402 declared extensions.eip2612GasSponsoring

    @property
    def ceiling_usd(self) -> float:
        return self.amount / 1e6


def gas_sponsoring_declared(payment_required: dict[str, Any]) -> bool:
    """Whether the 402's top-level ``extensions`` declares ``eip2612GasSponsoring``."""
    extensions = payment_required.get("extensions")
    return isinstance(extensions, dict) and bool(extensions.get(EIP2612_GAS_SPONSORING_KEY))


def offers_upto(payment_required: dict[str, Any]) -> bool:
    """Whether any ``accepts`` entry is an upto requirement (usable or not)."""
    accepts = payment_required.get("accepts")
    return isinstance(accepts, list) and any(
        isinstance(o, dict) and o.get("scheme") == "upto" for o in accepts
    )


def find_upto_option(payment_required: dict[str, Any]) -> UptoOption | None:
    """The first upto requirement this SDK can sign, or ``None``.

    Same trust rule as ``exact`` (see ``EVM_NETWORKS``): the 402 selects a
    network the SDK knows and must ask for that network's USDC; the chain id and
    token domain come from the SDK's table. ``extra.facilitatorAddress`` is
    required — without it the witness cannot bind a settler, and the official
    client refuses too.
    """
    accepts = payment_required.get("accepts")
    if not isinstance(accepts, list):
        return None
    sponsoring = gas_sponsoring_declared(payment_required)
    for opt in accepts:
        if not isinstance(opt, dict) or opt.get("scheme") != "upto":
            continue
        try:
            option = _validate_upto_option(opt, sponsoring)
        except (TypeError, ValueError) as exc:
            logger.debug("x402 upto: ignoring upto offer (%s)", exc)
            continue
        return option
    return None


def _validate_upto_option(opt: dict[str, Any], sponsoring: bool) -> UptoOption:
    network = str(opt.get("network") or "")
    net = EVM_NETWORKS.get(_NETWORK_ALIASES.get(network, network))
    if net is None:
        raise ValueError(f"network {network!r} is not an EVM network this SDK signs on")

    asset = opt.get("asset")
    if not isinstance(asset, str) or asset.lower() != net["usdc"].lower():
        raise ValueError(f"asset {asset!r} is not USDC on {network}")

    raw_extra = opt.get("extra")
    extra: dict[str, Any] = raw_extra if isinstance(raw_extra, dict) else {}
    facilitator = extra.get("facilitatorAddress")
    if not isinstance(facilitator, str) or not _ADDRESS_RE.match(facilitator):
        raise ValueError("no extra.facilitatorAddress")

    pay_to = opt.get("payTo")
    if not isinstance(pay_to, str) or not _ADDRESS_RE.match(pay_to):
        raise ValueError(f"payTo {pay_to!r} is not an address")

    raw_amount = opt.get("amount") or opt.get("maxAmountRequired")
    if not _UINT_RE.match(str(raw_amount or "")) or int(str(raw_amount)) <= 0:
        raise ValueError(f"amount {raw_amount!r} is not a positive integer")

    timeout = opt.get("maxTimeoutSeconds", 300)
    if isinstance(timeout, bool) or not isinstance(timeout, int) or timeout <= 0:
        raise ValueError(f"maxTimeoutSeconds {timeout!r} is not a positive integer")

    return UptoOption(
        requirement=dict(opt),
        network=_NETWORK_ALIASES.get(network, network),
        chain_id=int(net["chain_id"]),
        usdc=to_checksum_address(net["usdc"]),
        domain=dict(net["domain"]),
        rpcs=tuple(net.get("rpcs") or ()),
        amount=int(str(raw_amount)),
        pay_to=to_checksum_address(pay_to),
        facilitator=to_checksum_address(facilitator),
        max_timeout_seconds=timeout,
        gas_sponsoring=sponsoring,
    )


