@dataclass(frozen=True)
class UptoChainState:
    balance: int  # USDC balanceOf(owner)
    allowance: int  # USDC allowance(owner, Permit2)
    permit_nonce: int | None  # USDC nonces(owner); read only when a permit is needed


def _word(address: str) -> str:
    return address[2:].lower().rjust(64, "0")


def _eth_call_body(to: str, data: str) -> dict[str, Any]:
    return {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "eth_call",
        "params": [{"to": to, "data": data}, "latest"],
    }


def _parse_uint(payload: Any) -> int:
    """A uint256 eth_call result, strictly: an RPC error or empty return raises.

    Strict on purpose — a nonce misread as 0 signs a permit the token rejects,
    which would fail a call that ``exact`` would have paid for.
    """
    if not isinstance(payload, dict) or payload.get("error"):
        raise UptoUnavailable(f"eth_call error: {payload!r:.200}")
    result = payload.get("result")
    if not isinstance(result, str) or not result.startswith("0x") or len(result) <= 2:
        raise UptoUnavailable(f"eth_call returned {result!r:.80}")
    return int(result, 16)


def _state_calls(option: UptoOption, owner: str) -> tuple[tuple[str, str], tuple[str, str]]:
    return (
        (option.usdc, _SEL_BALANCE_OF + _word(owner)),
        (option.usdc, _SEL_ALLOWANCE + _word(owner) + _word(PERMIT2_ADDRESS)),
    )


def _nonce_call(option: UptoOption, owner: str) -> tuple[str, str]:
    return option.usdc, _SEL_NONCES + _word(owner)


def _needs_permit_nonce(option: UptoOption, allowance: int) -> bool:
    return option.gas_sponsoring and allowance < option.amount


def _read_state_sync(
    http: httpx.Client, url: str, option: UptoOption, owner: str
) -> UptoChainState:
    def call(to: str, data: str) -> int:
        resp = http.post(url, json=_eth_call_body(to, data))
        resp.raise_for_status()
        return _parse_uint(resp.json())

    (b_to, b_data), (a_to, a_data) = _state_calls(option, owner)
    balance = call(b_to, b_data)
    allowance = call(a_to, a_data)
    nonce = call(*_nonce_call(option, owner)) if _needs_permit_nonce(option, allowance) else None
    return UptoChainState(balance, allowance, nonce)


async def _read_state_async(
    http: httpx.AsyncClient, url: str, option: UptoOption, owner: str
) -> UptoChainState:
    async def call(to: str, data: str) -> int:
        resp = await http.post(url, json=_eth_call_body(to, data))
        resp.raise_for_status()
        return _parse_uint(resp.json())

    (b_to, b_data), (a_to, a_data) = _state_calls(option, owner)
    balance = await call(b_to, b_data)
    allowance = await call(a_to, a_data)
    nonce = (
        await call(*_nonce_call(option, owner)) if _needs_permit_nonce(option, allowance) else None
    )
    return UptoChainState(balance, allowance, nonce)


def read_upto_chain_state(
    option: UptoOption, owner: str, *, timeout: float = RPC_TIMEOUT_SECONDS
) -> UptoChainState:
    """Read balance, Permit2 allowance and (if a permit is needed) the EIP-2612 nonce.

    Tries each of the network's public RPCs in turn; raises
    :class:`UptoUnavailable` when none answers.
    """
    if not option.rpcs:
        raise UptoUnavailable(f"no public RPC configured for {option.network}")
    last: Exception | None = None
    for url in option.rpcs:
        try:
            with httpx.Client(timeout=timeout) as http:
                return _read_state_sync(http, url, option, owner)
        except Exception as exc:  # next RPC
            last = exc
    raise UptoUnavailable(f"every RPC for {option.network} failed: {last}") from last


async def aread_upto_chain_state(
    option: UptoOption, owner: str, *, timeout: float = RPC_TIMEOUT_SECONDS
) -> UptoChainState:
    """Async :func:`read_upto_chain_state` — the same reads, without blocking the loop."""
    if not option.rpcs:
        raise UptoUnavailable(f"no public RPC configured for {option.network}")
    last: Exception | None = None
    for url in option.rpcs:
        try:
            async with httpx.AsyncClient(timeout=timeout) as http:
                return await _read_state_async(http, url, option, owner)
        except Exception as exc:  # next RPC
            last = exc
    raise UptoUnavailable(f"every RPC for {option.network} failed: {last}") from last


# ---------------------------------------------------------------------------
# Deciding
# ---------------------------------------------------------------------------

# Sponsored permits this process signed and has not yet seen consumed:
# (network, owner) → (USDC nonce signed over, permit deadline). A permit lands
# only when the facilitator settles the call that carried it, and it approves
# just that call's ceiling, so Permit2's allowance is back near 0 afterwards and
# every sponsored call needs a fresh permit. Until one lands the chain still
# shows the old USDC nonce, and a second call would sign another permit over the
# SAME nonce: the first settlement consumes it and the second reverts on-chain
# (seen live on Base mainnet). So per wallet and network only one gas-sponsored
# upto payment is in flight; a call that would need a second pays exact.
#
# Read on every sponsored preflight: on-chain nonce > signed nonce → the permit
# was consumed, clear; ≤ and before the deadline → still in flight, pay exact;
# past the deadline → it can never land, clear.
_PERMITS_IN_FLIGHT: dict[tuple[str, str], tuple[int, int]] = {}
_PERMITS_LOCK = threading.Lock()


def _now() -> float:
    return time.time()


def _claim_permit_slot(network: str, owner: str, onchain_nonce: int, deadline: int) -> bool:
    """Atomically: if no permit is in flight for this wallet+network, record one
    over ``onchain_nonce`` (valid until ``deadline``) and return True."""
    key = (network, owner.lower())
    now = _now()
    with _PERMITS_LOCK:
        pending = _PERMITS_IN_FLIGHT.get(key)
        if pending is not None:
            signed_nonce, pending_deadline = pending
            if onchain_nonce <= signed_nonce and now < pending_deadline:
                return False
        _PERMITS_IN_FLIGHT[key] = (onchain_nonce, deadline)
        return True


def _release_permit_slot(network: str, owner: str, signed_nonce: int) -> None:
    """Forget a permit that was never sent (signing failed)."""
    key = (network, owner.lower())
    with _PERMITS_LOCK:
        pending = _PERMITS_IN_FLIGHT.get(key)
        if pending is not None and pending[0] == signed_nonce:
            del _PERMITS_IN_FLIGHT[key]


def plan_upto(option: UptoOption, state: UptoChainState) -> bool | None:
    """``False`` = upto with no permit, ``True`` = upto with a sponsored permit,
    ``None`` = fall back to exact."""
    if state.balance < option.amount:
        logger.debug(
            "x402 upto: USDC balance %s below ceiling %s; using exact",
            state.balance,
            option.amount,
        )
        return None
    if state.allowance >= option.amount:
        return False
    if option.gas_sponsoring and state.permit_nonce is not None:
        return True
    logger.debug(
        "x402 upto: Permit2 allowance %s below ceiling %s and no gas sponsoring; using exact",
        state.allowance,
        option.amount,
    )
    return None


