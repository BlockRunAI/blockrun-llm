logger = logging.getLogger(__name__)

# Canonical Uniswap Permit2 — the same address on every EVM chain.
PERMIT2_ADDRESS = "0x000000000022D473030F116dDEE9F6B43aC78BA3"
# x402's upto proxy: the Permit2 `spender`. It only lets the facilitator bound
# in the witness settle, and only up to the permitted amount.
X402_UPTO_PERMIT2_PROXY_ADDRESS = "0x4020A4f3b7b90ccA423B9fabCc0CE57C6C240002"

EIP2612_GAS_SPONSORING_KEY = "eip2612GasSponsoring"
# The EIP-2612 permit approves Permit2 for exactly the per-call ceiling, as the
# official client does. Not MaxUint256: the upto proxy's `_executePermit`
# reverts with Permit2612AmountMismatch unless permit.value == permitted.amount,
# and CDP /verify rejects a MaxUint256 permit.
EIP2612_GAS_SPONSORING_VERSION = "1"

# `payment_scheme` values a client accepts. "auto" prefers upto when the rule
# above allows it; "exact" never signs upto.
PAYMENT_SCHEMES = ("auto", "exact")
PAYMENT_SCHEME_ENV = "BLOCKRUN_PAYMENT_SCHEME"

# Per-RPC timeout for the allowance / balance / nonce reads. These run on every
# upto-eligible call before signing, so they are kept short: a slow RPC falls
# through to the next one, and all of them failing falls back to exact.
RPC_TIMEOUT_SECONDS = 3.0

# ERC-20 / EIP-2612 view selectors.
_SEL_BALANCE_OF = "0x70a08231"  # balanceOf(address)
_SEL_ALLOWANCE = "0xdd62ed3e"  # allowance(address,address)
_SEL_NONCES = "0x7ecebe00"  # nonces(address)

_ADDRESS_RE = re.compile(r"^0x[0-9a-fA-F]{40}$")
_UINT_RE = re.compile(r"^[0-9]+$")

UPTO_PERMIT2_WITNESS_TYPES: dict[str, list[dict[str, str]]] = {
    "PermitWitnessTransferFrom": [
        {"name": "permitted", "type": "TokenPermissions"},
        {"name": "spender", "type": "address"},
        {"name": "nonce", "type": "uint256"},
        {"name": "deadline", "type": "uint256"},
        {"name": "witness", "type": "Witness"},
    ],
    "TokenPermissions": [
        {"name": "token", "type": "address"},
        {"name": "amount", "type": "uint256"},
    ],
    "Witness": [
        {"name": "to", "type": "address"},
        {"name": "facilitator", "type": "address"},
        {"name": "validAfter", "type": "uint256"},
    ],
}

EIP2612_PERMIT_TYPES: dict[str, list[dict[str, str]]] = {
    "Permit": [
        {"name": "owner", "type": "address"},
        {"name": "spender", "type": "address"},
        {"name": "value", "type": "uint256"},
        {"name": "nonce", "type": "uint256"},
        {"name": "deadline", "type": "uint256"},
    ],
}


class UptoUnavailable(Exception):
    """Upto cannot be used for this call; the caller falls back to exact."""


def resolve_payment_scheme(value: str | None) -> str:
    """The client's ``payment_scheme``: the argument, else ``BLOCKRUN_PAYMENT_SCHEME``, else "auto".

    Raises:
        ValueError: For anything other than "auto" or "exact".
    """
    raw = value if value is not None else os.environ.get(PAYMENT_SCHEME_ENV)
    scheme = (raw or "auto").strip().lower()
    if scheme not in PAYMENT_SCHEMES:
        source = "payment_scheme" if value is not None else PAYMENT_SCHEME_ENV
        raise ValueError(f'{source} must be one of {", ".join(PAYMENT_SCHEMES)}; got "{raw}"')
    return scheme


