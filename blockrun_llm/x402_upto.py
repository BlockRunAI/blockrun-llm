def settled_upto_amount(settlement: dict[str, Any] | None, ceiling: int) -> int | None:
    """The settled micro-USDC a ``PAYMENT-RESPONSE`` reports, if it reports one
    that is plausible for this ceiling (0 ≤ amount ≤ ceiling); else ``None``."""
    if not settlement:
        return None
    raw = settlement.get("amount_micro_usdc")
    if raw is None or not _UINT_RE.match(str(raw)):
        return None
    amount = int(str(raw))
    return amount if amount <= ceiling else None


